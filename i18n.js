  var PT_COUNTRIES = ['BR', 'PT', 'AO', 'MZ', 'CV', 'GW', 'ST', 'TL'];
  var ES_COUNTRIES = ['AR', 'BO', 'CL', 'CO', 'CR', 'CU', 'DO', 'EC', 'SV', 'GQ', 'GT', 'HN', 'MX', 'NI', 'PA', 'PY', 'PE', 'PR', 'ES', 'UY', 'VE'];

  function countryToLang(country) {
    if (!country) return null;
    var c = country.toUpperCase();
    if (PT_COUNTRIES.indexOf(c) !== -1) return 'pt';
    if (ES_COUNTRIES.indexOf(c) !== -1) return 'es';
    return 'en';
  }

  function browserLang() {
    var lang = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
    if (lang.startsWith('pt')) return 'pt';
    if (lang.startsWith('es')) return 'es';
    return 'en';
  }

  function applyTranslations(lang) {
    var t = i18n[lang] || i18n.en;
    var langAttr = { pt: 'pt-BR', en: 'en', es: 'es' }[lang] || 'en';
    document.documentElement.lang = langAttr;

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (t[key] !== undefined) {
        el.innerHTML = t[key];
      }
    });

    if (!document.documentElement.hasAttribute('data-preserve-page-meta')) {
      document.title = t.meta_title;
      var metaDesc = document.querySelector('meta[name="description"]');
      if (metaDesc) metaDesc.setAttribute('content', t.meta_desc);
    }

  }

  function init() {
    var initial = browserLang();
    applyTranslations(initial);

    fetch('https://ipwho.is/?fields=country_code', { cache: 'no-store' })
      .then(function (r) { return r.json(); })
      .then(function (data) {
        var ipLang = countryToLang(data.country_code);
        if (ipLang && ipLang !== initial) {
          applyTranslations(ipLang);
        }
      })
      .catch(function () { });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
